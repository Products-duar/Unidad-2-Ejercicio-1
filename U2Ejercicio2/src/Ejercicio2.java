    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
       try {
            String usuario = Nombre.getText().trim();
            String pais = País.getText().trim();
            String tipoMoneda = Moneda.getText().trim().toLowerCase();
            
            if (usuario.isEmpty() || pais.isEmpty() || tipoMoneda.isEmpty() || Cantidad.getText().trim().isEmpty()) {
                JOptionPane.showMessageDialog(this, "Por favor, complete todos los campos.", "Campos vacíos", JOptionPane.WARNING_MESSAGE);
                return;
            }

            double quetzales = Double.parseDouble(Cantidad.getText().trim());
            double resultadoConvertido = 0.0;
            String simbolo = "";

            // Tasas de conversión: Dólar Q7.80, Euro Q8.50, Peso Q0.40[cite: 4]
            if (tipoMoneda.equals("dolar") || tipoMoneda.equals("dólares")) {
                resultadoConvertido = quetzales / 7.80;
                simbolo = "$";
            } else if (tipoMoneda.equals("euro") || tipoMoneda.equals("euros")) {
                resultadoConvertido = quetzales / 8.50;
                simbolo = "€";
            } else if (tipoMoneda.equals("peso") || tipoMoneda.equals("pesos")) {
                resultadoConvertido = quetzales / 0.40;
                simbolo = "$"; 
            } else {
                JOptionPane.showMessageDialog(this, "Moneda no válida.\nEscriba: dolar, euro o peso.", "Error", JOptionPane.ERROR_MESSAGE);
                return;
            }
            String mensaje = "====== CONVERSIÓN ======\n\n" +
                             "Usuario: " + usuario + "\n" +
                             "País destino: " + pais + "\n" +
                             "Moneda seleccionada: " + Moneda.getText().trim() + "\n" +
                             "Cantidad en quetzales: Q" + quetzales + "\n" +
                             "Resultado convertido: " + simbolo + String.format("%.2f", resultadoConvertido);

            JOptionPane.showMessageDialog(this, mensaje, "Resultado de Conversión", JOptionPane.INFORMATION_MESSAGE);

        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(this, "El campo 'Cantidad en quetzales' debe ser un número válido.", "Error de formato", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_jButton1ActionPerformed

