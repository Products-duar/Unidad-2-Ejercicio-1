    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
        try {
            String nombreCliente = Cliente.getText().trim();
            String tipoCliente = TdCliente.getText().trim().toLowerCase();
            
            if (nombreCliente.isEmpty() || tipoCliente.isEmpty() || Compra.getText().trim().isEmpty()) {
                JOptionPane.showMessageDialog(this, "Por favor, complete todos los campos.", "Campos vacíos", JOptionPane.WARNING_MESSAGE);
                return;
            }

            double compraTotal = Double.parseDouble(Compra.getText().trim());
            double porcentajeDescuento = 0.0;
            String textoDescuento = "0%";

            // Descuentos requeridos
            if (tipoCliente.equals("estudiante")) {
                porcentajeDescuento = 0.10;
                textoDescuento = "10%";
            } else if (tipoCliente.equals("docente")) {
                porcentajeDescuento = 0.20;
                textoDescuento = "20%";
            } else if (tipoCliente.equals("invitado")) {
                porcentajeDescuento = 0.0;
                textoDescuento = "0%";
            } else {
                JOptionPane.showMessageDialog(this, "Tipo de cliente no válido.\nEscriba: estudiante, docente o invitado.", "Error", JOptionPane.ERROR_MESSAGE);
                return;
            }

            double descuento = compraTotal * porcentajeDescuento;
            double totalAPagar = compraTotal - descuento;

            // Formato de la factura solicitado
            String factura = "====== FACTURA ======\n\n" +
                             "Cliente: " + nombreCliente + "\n" +
                             "Tipo de cliente: " + TdCliente.getText().trim() + "\n" +
                             "Compra total: Q" + compraTotal + "\n" +
                             "Descuento aplicado: " + textoDescuento + "\n" +
                             "Total a pagar: Q" + totalAPagar;

            JOptionPane.showMessageDialog(this, factura, "Resultado de Factura", JOptionPane.INFORMATION_MESSAGE);

        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(this, "El campo 'Total de Compra' debe ser un número válido.", "Error de formato", JOptionPane.ERROR_MESSAGE);
            }
    }//GEN-LAST:event_jButton1ActionPerformed

